#!/usr/bin/env bash
set -euo pipefail

DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SECRETS_FILE="$DIR/src/secrets.h"
CACHE="${XDG_CACHE_HOME:-$HOME/.cache}/playr/ccache"
mkdir -p "$CACHE"

DO_FLASH=0
RECONFIGURE=0
PORT="/dev/ttyUSB0"
BAUD="115200"

usage() {
    cat <<EOF
Usage: ./build.sh [OPTIONS]

Compiles your personalized O-LED (oled_wled) firmware binary (.bin) with your Wi-Fi
credentials and companion WLED-SR IP.

Options:
  --reconfigure        Prompt for Wi-Fi SSID, Password, and WLED-SR IP even if src/secrets.h exists
  --flash [PORT]       Build and flash to ESP32 (default port: /dev/ttyUSB0)
  --baud <BAUD>        Serial baud rate when flashing (default: 115200)
  -h, --help           Show this help message
EOF
}

while [[ $# -gt 0 ]]; do
    case "$1" in
        --reconfigure|-r)
            RECONFIGURE=1
            shift
            ;;
        --flash|-f)
            DO_FLASH=1
            if [[ $# -gt 1 && "$2" != --* ]]; then
                PORT="$2"
                shift 2
            else
                shift
            fi
            ;;
        --baud|-b)
            BAUD="${2:-115200}"
            shift 2
            ;;
        -h|--help)
            usage
            exit 0
            ;;
        *)
            echo "Unknown option: $1"
            usage
            exit 1
            ;;
    esac
done

escape_c_string() {
    local s="$1"
    s="${s//\\/\\\\}"
    s="${s//\"/\\\"}"
    printf '%s' "$s"
}

if [[ ! -f "$SECRETS_FILE" || "$RECONFIGURE" -eq 1 ]]; then
    echo "============================================================"
    echo "  O-LED (oled_wled) — First-Time Wi-Fi & WLED-SR Setup"
    echo "============================================================"
    read -r -p "1) Enter your 2.4GHz Wi-Fi SSID: " INPUT_SSID
    while [[ -z "$INPUT_SSID" ]]; do
        read -r -p "   Wi-Fi SSID cannot be empty. Enter Wi-Fi SSID: " INPUT_SSID
    done

    read -r -s -p "2) Enter your Wi-Fi Password: " INPUT_PASS
    echo ""

    read -r -p "3) Enter companion WLED-SR IP [default: 192.168.1.100]: " INPUT_TUUB_IP
    INPUT_TUUB_IP="${INPUT_TUUB_IP:-192.168.1.100}"

    ESC_SSID="$(escape_c_string "$INPUT_SSID")"
    ESC_PASS="$(escape_c_string "$INPUT_PASS")"
    ESC_IP="$(escape_c_string "$INPUT_TUUB_IP")"

    cat > "$SECRETS_FILE" <<EOF
#pragma once

// Local Wi-Fi and WLED companion configuration (gitignored - generated by ./build.sh)
#define WIFI_SSID_SECRET    "${ESC_SSID}"
#define WIFI_PASS_SECRET    "${ESC_PASS}"
#define TUUB_LAYT_IP_SECRET "${ESC_IP}"
EOF
    echo "[OK] Saved credentials to src/secrets.h (gitignored)."
    echo ""
else
    echo "[INFO] Using existing src/secrets.h (run './build.sh --reconfigure' to change Wi-Fi settings)."
fi

BUILD_CMD='
set -e
if [ -n "${IDF_PATH:-}" ] && [ -f "$IDF_PATH/export.sh" ]; then
    . "$IDF_PATH/export.sh" >/dev/null
fi
idf.py build
esptool.py --chip esp32 merge_bin \
    -o build/oled_wled_factory_0x0.bin \
    --flash_mode dio --flash_freq 40m --flash_size 4MB \
    0x1000 build/bootloader/bootloader.bin \
    0x8000 build/partition_table/partition-table.bin \
    0x10000 build/oled_wled.bin
'

if command -v idf.py >/dev/null 2>&1; then
    echo "[BUILD] Building with local ESP-IDF..."
    (cd "$DIR" && bash -c "$BUILD_CMD")
elif command -v docker >/dev/null 2>&1; then
    if docker image inspect sle118/squeezelite-esp32-idfv448:4.4.8 >/dev/null 2>&1; then
        DOCKER_IMAGE="sle118/squeezelite-esp32-idfv448:4.4.8"
    else
        DOCKER_IMAGE="espressif/idf:release-v4.4"
    fi
    echo "[BUILD] Building inside Docker container ($DOCKER_IMAGE)..."
    docker run --rm \
        -v "$DIR:/project" -w /project \
        -v "$CACHE:/ccache" -e CCACHE_DIR=/ccache \
        --user "$(id -u):$(id -g)" -e HOME=/tmp \
        "$DOCKER_IMAGE" \
        bash -c "$BUILD_CMD"
else
    echo "[ERROR] Neither 'idf.py' nor 'docker' was found on your system."
    echo "        Install Docker (https://docs.docker.com/get-docker/) or use the GitHub Actions Cloud Builder!"
    exit 1
fi

echo ""
echo "============================================================"
echo "  Build Complete!"
echo "============================================================"
echo "  • All-in-one Factory Binary (flash @ 0x0):     build/oled_wled_factory_0x0.bin"
echo "  • App-only Binary           (flash @ 0x10000): build/oled_wled.bin"
echo "============================================================"

if [[ "$DO_FLASH" -eq 1 ]]; then
    echo "[FLASH] Flashing ESP32 on $PORT @ ${BAUD} baud..."
    "$DIR/flash.sh" "$PORT" "$BAUD"
fi
